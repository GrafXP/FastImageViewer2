# Compiles every entry point listed below with fxc and writes, into shaders\out:
#   <name>.cso      bytecode
#   <name>.h        C++ header:  const BYTE g_<name>[]
#   Shaders.g.cs    C#:          Fiv.Shaders.<Name> as ReadOnlySpan<byte> (stored in the exe's read-only data)
# Skips the work when the outputs are newer than the sources.
$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
$out = Join-Path $root 'out'

# file, entry point, profile, output name
$shaders = @(
    @('blit.hlsl', 'vs_main', 'vs_5_0', 'blit_vs'),
    @('blit.hlsl', 'ps_main', 'ps_5_0', 'blit_ps'),
    @('view.hlsl', 'vs_main', 'vs_5_0', 'view_vs'),
    @('view.hlsl', 'ps_main', 'ps_5_0', 'view_ps'),
    @('view.hlsl', 'ps_raw', 'ps_5_0', 'view_raw_ps'),
    @('combine.hlsl', 'vs_main', 'vs_5_0', 'combine_vs'),
    @('combine.hlsl', 'ps_main', 'ps_5_0', 'combine_ps'),
    @('surface.hlsl', 'vs_main', 'vs_5_0', 'surface_vs'),
    @('surface.hlsl', 'ps_main', 'ps_5_0', 'surface_ps')
)

$cs = Join-Path $out 'Shaders.g.cs'
$sources = Get-ChildItem $root -File | Where-Object { $_.Extension -in '.hlsl', '.hlsli', '.ps1' }
if ((Test-Path $cs) -and -not ($sources | Where-Object { $_.LastWriteTimeUtc -gt (Get-Item $cs).LastWriteTimeUtc })) { return }

$fxc = Get-ChildItem "${env:ProgramFiles(x86)}\Windows Kits\10\bin\*\x64\fxc.exe" |
    Sort-Object { [version]$_.Directory.Parent.Name } | Select-Object -Last 1
if (-not $fxc) { throw 'fxc.exe not found; install the Windows SDK' }

New-Item -ItemType Directory -Force $out | Out-Null
$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine('// <auto-generated> by shaders\build.ps1 </auto-generated>')
[void]$sb.AppendLine('namespace Fiv;')
[void]$sb.AppendLine('internal static class Shaders')
[void]$sb.AppendLine('{')
foreach ($s in $shaders) {
    $file, $entry, $profile, $name = $s
    $cso = Join-Path $out "$name.cso"
    & $fxc.FullName /nologo /O3 /T $profile /E $entry /Fo $cso /Fh (Join-Path $out "$name.h") /Vn "g_$name" (Join-Path $root $file) | Out-Null
    if ($LASTEXITCODE) { throw "fxc failed for $file $entry" }
    $bytes = [System.IO.File]::ReadAllBytes($cso)
    $member = -join ($name -split '_' | ForEach-Object { $_.Substring(0, 1).ToUpper() + $_.Substring(1) })
    [void]$sb.Append("    public static System.ReadOnlySpan<byte> $member => [")
    [void]$sb.Append(($bytes -join ','))
    [void]$sb.AppendLine('];')
}
[void]$sb.AppendLine('}')
[System.IO.File]::WriteAllText($cs, $sb.ToString())
